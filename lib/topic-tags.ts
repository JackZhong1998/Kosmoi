export type GardenSeed = {
  id: string;
  label: string;
  level: number;
  parent?: string;
};

function pickSpread<T>(arr: T[], n: number): T[] {
  if (arr.length <= n) return arr;
  const out: T[] = [];
  const step = arr.length / n;
  for (let i = 0; i < n; i++) out.push(arr[Math.floor(i * step + step / 3) % arr.length]);
  return [...new Set(out)];
}

export function getRoots(audience: Audience, locale: 'en' | 'zh' = 'zh'): TagBranch[] {
  return (locale === 'en' ? EN_TOPIC_TREE : TOPIC_TREE)[audience];
}

export function getChildren(audience: Audience, path: string[], locale: 'en' | 'zh' = 'zh'): string[] {
  const tree = locale === 'en' ? EN_TOPIC_TREE : TOPIC_TREE;
  if (path.length === 0) return tree[audience].map((n) => n.label);
  const l1 = tree[audience].find((n) => n.label === path[0]);
  if (!l1) return [];
  if (path.length === 1) return Object.keys(l1.children);
  if (path.length === 2) return l1.children[path[1]] ?? [];
  return [];
}

export function getGardenSeeds(audience: Audience, locale: 'en' | 'zh' = 'zh'): GardenSeed[] {
  return (locale === 'en' ? EN_TOPIC_TREE : TOPIC_TREE)[audience].map((l1) => ({ id: l1.label, label: l1.label, level: 0 }));
}

export function randomSibling(audience: Audience, path: string[]): string[] {
  if (path.length === 0) return path;
  if (path.length === 1) {
    const kids = getChildren(audience, path);
    if (!kids.length) return path;
    return [...path, kids[Math.floor(Math.random() * kids.length)]];
  }
  const parent = path.slice(0, -1);
  const siblings = getChildren(audience, parent).filter((label) => label !== path[path.length - 1]);
  if (!siblings.length) return path;
  const next = [...path];
  next[next.length - 1] = siblings[Math.floor(Math.random() * siblings.length)];
  return next;
}

export function audienceLabel(id: Audience, locale: 'en' | 'zh' = 'zh'): string {
  if (locale === 'en') return id === 'female' ? 'For women' : id === 'male' ? 'For men' : 'For everyone';
  return AUDIENCES.find((item) => item.id === id)?.label || id;
}
