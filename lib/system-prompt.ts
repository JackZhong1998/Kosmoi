- 改人物：增减角色、改欲望/缺点/底线/登场方式/专属路线。
- 改情节：某一章事件、选择、汇合点、时间线。
- 改结局：结局数量、差异、门槛、谁留下谁离开。
- 改文风：叙述距离、幽默浓度、荤/甜/冷、句子长短、是否第二人称、是否更像剧本。
